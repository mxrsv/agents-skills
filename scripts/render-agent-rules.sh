#!/usr/bin/env bash
# Sinh bộ luật dạng văn bản từ nguồn canonical ~/.claude/CLAUDE.md + output style đang bật + rules/core/ + rules/docs/,
# nối thêm phần riêng của từng đích ở templates/<đích>-extra.md:
#   (không tham số)  → ghi ~/.codex/AGENTS.md (+ codex-extra.md).
#   --cloud          → in ra stdout một setup script cho cloud environment ở claude.ai/code (+ cloud-extra.md).
#                      Script đó ghi ~/.claude/CLAUDE.md trong VM (docs: "Add personal preferences without
#                      committing to the repo") cùng các file mà luật trỏ tới theo path (CLOUD_FILES).
#                      Dùng: render-agent-rules.sh --cloud | pbcopy → dán vào ô Setup script của environment.
# Chạy lại mỗi khi rules đổi. KHÔNG sửa tay file đích — mọi sửa sẽ bị ghi đè;
# nội dung riêng cho từng đích phải nằm ở templates/<đích>-extra.md (được git track).
set -eu
SRC="$HOME/.claude"
TARGET=codex
[ "${1:-}" = "--cloud" ] && TARGET=cloud
EXTRA="$SRC/templates/$TARGET-extra.md"
OUT="$HOME/.codex/AGENTS.md"
# File luật nhắc tới bằng path nhưng không nối vào CLAUDE.md (template, rules nạp theo path) — chép nguyên vào VM.
CLOUD_FILES="templates/project-structure.md templates/AGENTS.template.md rules/react/patterns.md rules/typescript/coding-style.md rules/typescript/patterns.md"
EOF_MARK="__AGENT_RULES_EOF__"
# Output style đang bật (settings.json → outputStyle, khớp với `name:` trong output-styles/*.md).
# Codex và cloud session không đọc output style của máy này nên thân style được nối thẳng vào bộ luật.
STYLE_NAME=$(jq -r '.outputStyle // empty' "$SRC/settings.json" 2>/dev/null || true)
STYLE_FILE=""
[ -n "$STYLE_NAME" ] && STYLE_FILE=$(grep -lx "name: $STYLE_NAME" "$SRC"/output-styles/*.md 2>/dev/null | head -1 || true)
[ -f "$EXTRA" ] || { echo "❌ thiếu $EXTRA — dừng để không mất phần riêng của $TARGET" >&2; exit 1; }
# Bỏ block YAML frontmatter đầu file (--- ... ---) nếu có.
strip_frontmatter() {
  awk 'NR==1 && $0=="---" { infm=1; next } infm && $0=="---" { infm=0; next } !infm' "$1"
}

render_rules() {
  if [ "$TARGET" = cloud ]; then
    echo "<!-- GENERATED by ~/.claude/scripts/render-agent-rules.sh --cloud on the owner's machine — do NOT edit here. -->"
    echo "<!-- Source: ~/.claude/CLAUDE.md + active output style + rules/core/*.md + rules/docs/*.md + templates/cloud-extra.md -->"
    echo
    echo "> **Platform limit:** a cloud session only receives the TEXT layer. Hooks from the owner's"
    echo "> \`~/.claude/settings.json\` (e.g. \`file-guard.sh\`) do not run here. Follow the D-rules below by discipline."
  else
    echo "<!-- GENERATED by ~/.claude/scripts/render-agent-rules.sh — do NOT edit by hand. -->"
    echo "<!-- Source: ~/.claude/CLAUDE.md + active output style + rules/core/*.md + rules/docs/*.md + templates/codex-extra.md -->"
    echo
    echo "> **Platform limit:** Codex only receives the TEXT layer. Claude Code's \`file-guard.sh\` hook"
    echo "> does not run here. Follow the D-rules below by discipline, not by enforcement."
  fi
  echo
  cat "$SRC/CLAUDE.md"
  if [ -n "$STYLE_FILE" ]; then
    echo; echo "---"; echo
    strip_frontmatter "$STYLE_FILE"
  fi
  # Codex và cloud nhận toàn bộ luật dạng văn bản — rules/docs/ (nạp theo path ở Claude Code local)
  # được nối luôn vào đây, bỏ frontmatter.
  for f in "$SRC"/rules/core/*.md "$SRC"/rules/docs/*.md; do
    [ -f "$f" ] || continue
    echo; echo "---"; echo
    strip_frontmatter "$f"
  done
  echo; echo "---"; echo
  cat "$EXTRA"
}

# In một lệnh heredoc ghi nội dung stdin vào $HOME/.claude/<$1> khi setup script chạy.
emit_file() {
  body=$(cat)
  if printf '%s\n' "$body" | grep -qx "$EOF_MARK"; then
    echo "❌ $1 chứa dòng $EOF_MARK — đổi EOF_MARK" >&2; exit 1
  fi
  printf 'mkdir -p "$HOME/.claude/%s"\n' "$(dirname "$1")"
  printf "cat > \"\$HOME/.claude/%s\" <<'%s'\n%s\n%s\n" "$1" "$EOF_MARK" "$body" "$EOF_MARK"
}

render_cloud_setup() {
  rules=$(render_rules)
  echo "#!/bin/bash"
  echo "# GENERATED by ~/.claude/scripts/render-agent-rules.sh --cloud — re-render and paste again instead of editing."
  echo "# Rules bundle $(printf '%s\n' "$rules" | shasum -a 256 | cut -c1-12): the hash changes with the content, so a new paste rebuilds the environment cache."
  printf '%s\n' "$rules" | emit_file CLAUDE.md
  for f in $CLOUD_FILES; do
    emit_file "$f" < "$SRC/$f"
  done
  echo 'echo "✅ wrote ~/.claude/CLAUDE.md and rule files for cloud sessions"'
}

cleanup() { rm -f "$tmp_out"; }

if [ "$TARGET" = cloud ]; then
  # Render hết vào file tạm rồi mới in, để lỗi giữa chừng không để lại script cụt trong clipboard.
  tmp_out=$(mktemp "${TMPDIR:-/tmp}/agent-rules.XXXXXX")
  trap cleanup EXIT
  render_cloud_setup > "$tmp_out"
  cat "$tmp_out"
  echo "✅ đã in setup script cho cloud ($(wc -c < "$tmp_out" | tr -d ' ') byte) — dán vào Setup script của environment" >&2
  exit 0
fi

mkdir -p "$(dirname "$OUT")"
tmp_out=$(mktemp "${OUT}.tmp.XXXXXX")
trap cleanup EXIT
render_rules > "$tmp_out"
chmod 0644 "$tmp_out"
mv "$tmp_out" "$OUT"
trap - EXIT

echo "✅ đã sinh $OUT ($(wc -l < "$OUT" | tr -d ' ') dòng)"
